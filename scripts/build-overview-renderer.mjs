import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const result=await build({entryPoints:[new URL('vendor/playstunts/overview-entry.ts',root).pathname],bundle:true,format:'iife',globalName:'NativeOverview',write:false});
const banner='// PlayStunts native track-overview renderer (GPL-3.0-only).\n// Source: vendor/playstunts; upstream b5180b0a54193974c3b398ec38e6680db99f67cf.\n// Generated by esbuild 0.28.1; run scripts/build-overview-renderer.mjs to regenerate.\n';
writeFileSync(new URL('src/native-overview.js',root),banner+result.outputFiles[0].text+'\nexport { NativeOverview };\n');
